import { chromium } from 'playwright-core';
const EDGE = 'C:\\Program Files (x86)\\Microsoft\\Edge\\Application\\msedge.exe';
const browser = await chromium.launch({ executablePath: EDGE, headless: true, args: ['--use-angle=d3d11', '--enable-gpu'] });
const page = await browser.newPage({ viewport: { width: 1280, height: 720 } });
const errors = [];
page.on('pageerror', (e) => errors.push(e.message));
await page.goto('http://127.0.0.1:5179/?scene=exterior&intro=0', { waitUntil: 'load' });
await page.waitForFunction(() => window.__lab && window.__lab.ready);
await page.waitForTimeout(500);
const p0 = await page.evaluate(() => ({ x: window.__lab.camera.position.x, y: window.__lab.camera.position.y, z: window.__lab.camera.position.z, zoom: window.__lab.state.zoom }));
await page.waitForTimeout(2500);
const p1 = await page.evaluate(() => ({ x: window.__lab.camera.position.x, y: window.__lab.camera.position.y, z: window.__lab.camera.position.z, zoom: window.__lab.state.zoom }));
await page.mouse.move(640, 360);
await page.mouse.wheel(0, 700);
await page.waitForTimeout(1400);
const p2 = await page.evaluate(() => ({ x: window.__lab.camera.position.x, y: window.__lab.camera.position.y, z: window.__lab.camera.position.z, zoom: window.__lab.state.zoom }));
await page.screenshot({ path: 'shots/urgent/zoomed-live.png' });
console.log(JSON.stringify({ p0, p1, p2, moved: Math.hypot(p1.x - p0.x, p1.z - p0.z), errors }, null, 1));
await browser.close();
